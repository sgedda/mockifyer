/**
 * Self-contained drift report HTML generator.
 * Styled like Atlas HTML (atlas-doc-html.ts) for consistency.
 */

import type { DriftCheckReport, DriftHistoryReport, MockDriftReport } from './drift-report';

export interface DriftHtmlOptions {
  title?: string;
  includeSimulated?: boolean;
}

/**
 * Generate a self-contained HTML drift report.
 */
export function generateDriftHtml(
  report: DriftCheckReport | DriftHistoryReport,
  options: DriftHtmlOptions = {}
): string {
  const title = options.title || 'Mockifyer Drift Report';
  const timestamp = 'timestamp' in report ? report.timestamp : new Date().toISOString();
  
  const driftedReports = report.mockReports.filter((r) => r.hasDrift && !r.skipped && !r.notChecked);
  const cleanReports = report.mockReports.filter((r) => !r.hasDrift && !r.skipped && !r.notChecked);
  const skippedReports = report.mockReports.filter((r) => r.skipped);
  const notCheckedReports = report.mockReports.filter((r) => r.notChecked);

  const breakingReports = driftedReports.filter((r) => r.hasBreakingDrift);
  const warningReports = driftedReports.filter((r) => !r.hasBreakingDrift);

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="color-scheme" content="light">
  <title>${escapeHtml(title)}</title>
  <style>
    ${sharedCss()}
  </style>
</head>
<body>
  <div class="container">
    <header class="header">
      <h1>${escapeHtml(title)}</h1>
      <p class="subtitle">Contract drift detection for ${report.totalMocks} endpoint${report.totalMocks === 1 ? '' : 's'}</p>
      <p class="timestamp">Generated: ${formatTimestamp(timestamp)}</p>
    </header>

    ${generateSummarySection(report)}
    
    ${breakingReports.length > 0 ? generateDriftSection('Breaking Changes', breakingReports, 'breaking') : ''}
    ${warningReports.length > 0 ? generateDriftSection('Warnings', warningReports, 'warning') : ''}
    ${cleanReports.length > 0 ? generateCleanSection(cleanReports) : ''}
    ${notCheckedReports.length > 0 ? generateNotCheckedSection(notCheckedReports) : ''}
    ${skippedReports.length > 0 ? generateSkippedSection(skippedReports) : ''}

    <footer class="footer">
      <p>Generated by <a href="https://mockifyer.dev" target="_blank">Mockifyer</a> — API mock record/replay with drift detection</p>
      <p>Learn more: <a href="https://mockifyer.dev/docs/drift-check" target="_blank">Drift Check Documentation</a></p>
    </footer>
  </div>

  <script>
    // Toggle details
    document.querySelectorAll('.endpoint-header').forEach(header => {
      header.addEventListener('click', () => {
        const details = header.nextElementSibling;
        const isExpanded = details.style.display !== 'none';
        details.style.display = isExpanded ? 'none' : 'block';
        header.classList.toggle('collapsed', isExpanded);
      });
    });
    
    // Filter buttons
    const filterButtons = document.querySelectorAll('.filter-btn');
    const sections = document.querySelectorAll('.drift-section, .clean-section, .not-checked-section, .skipped-section');
    
    filterButtons.forEach(btn => {
      btn.addEventListener('click', () => {
        const filter = btn.dataset.filter;
        
        filterButtons.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        
        sections.forEach(section => {
          if (filter === 'all' || section.classList.contains(filter + '-section')) {
            section.style.display = 'block';
          } else {
            section.style.display = 'none';
          }
        });
      });
    });
  </script>
</body>
</html>`;
}

function generateSummarySection(report: DriftCheckReport | DriftHistoryReport): string {
  const statusClass = report.breakingDriftCount > 0 ? 'error' : 
                      report.warningOnlyCount > 0 ? 'warning' : 'success';
  const statusIcon = report.breakingDriftCount > 0 ? '🚨' : 
                     report.warningOnlyCount > 0 ? '⚠️' : '✅';
  const statusText = report.breakingDriftCount > 0 ? 'Breaking Changes Detected' :
                     report.warningOnlyCount > 0 ? 'Warnings Detected' : 'All Endpoints In Sync';

  return `
    <section class="summary-section">
      <div class="summary-card ${statusClass}">
        <h2>${statusIcon} ${statusText}</h2>
        <div class="summary-stats">
          <div class="stat">
            <div class="stat-value">${report.totalMocks}</div>
            <div class="stat-label">Total Endpoints</div>
          </div>
          <div class="stat">
            <div class="stat-value ${report.breakingDriftCount > 0 ? 'error-text' : ''}">${report.breakingDriftCount}</div>
            <div class="stat-label">Breaking</div>
          </div>
          <div class="stat">
            <div class="stat-value ${report.warningOnlyCount > 0 ? 'warning-text' : ''}">${report.warningOnlyCount}</div>
            <div class="stat-label">Warnings</div>
          </div>
          <div class="stat">
            <div class="stat-value">${report.totalMocks - report.driftedMocks - report.skippedCount - report.notCheckedCount}</div>
            <div class="stat-label">Clean</div>
          </div>
        </div>
      </div>

      <div class="filter-bar">
        <button class="filter-btn active" data-filter="all">All</button>
        ${report.breakingDriftCount > 0 ? '<button class="filter-btn" data-filter="breaking">Breaking</button>' : ''}
        ${report.warningOnlyCount > 0 ? '<button class="filter-btn" data-filter="warning">Warnings</button>' : ''}
        ${report.totalMocks - report.driftedMocks - report.skippedCount - report.notCheckedCount > 0 ? '<button class="filter-btn" data-filter="clean">Clean</button>' : ''}
      </div>
    </section>
  `;
}

function generateDriftSection(title: string, reports: MockDriftReport[], severity: 'breaking' | 'warning'): string {
  const sectionClass = severity === 'breaking' ? 'breaking-section' : 'warning-section';
  
  return `
    <section class="drift-section ${sectionClass}">
      <h2>${title} (${reports.length})</h2>
      ${reports.map(report => generateEndpointCard(report, severity)).join('\n')}
    </section>
  `;
}

function generateEndpointCard(report: MockDriftReport, severity: 'breaking' | 'warning'): string {
  const statusClass = severity === 'breaking' ? 'error' : 'warning';
  const statusIcon = severity === 'breaking' ? '✗' : '⚠';
  
  // Group issues by type
  const issuesByType = new Map<string, typeof report.issues>();
  for (const issue of report.issues) {
    const type = issue.type;
    if (!issuesByType.has(type)) {
      issuesByType.set(type, []);
    }
    issuesByType.get(type)!.push(issue);
  }

  const isSimulated = report.url.includes('localhost') || report.url.includes('127.0.0.1');
  const simulatedBadge = isSimulated ? '<span class="badge badge-simulated">Simulated</span>' : '';

  return `
    <div class="endpoint-card ${statusClass}">
      <div class="endpoint-header">
        <div class="endpoint-title">
          <span class="method-badge method-${report.method.toLowerCase()}">${escapeHtml(report.method)}</span>
          <span class="endpoint-url">${escapeHtml(report.url)}</span>
          ${simulatedBadge}
        </div>
        <span class="endpoint-status ${statusClass}-text">${statusIcon} ${report.issues.length} issue${report.issues.length === 1 ? '' : 's'}</span>
      </div>
      <div class="endpoint-details">
        ${report.mockFilePath ? `<div class="mock-file">📄 ${escapeHtml(report.mockFilePath)}</div>` : ''}
        
        <div class="issues-list">
          ${Array.from(issuesByType.entries()).map(([type, issues]) => `
            <div class="issue-group">
              <h4>${getIssueTypeLabel(type)}</h4>
              ${issues.map(issue => `
                <div class="issue-item ${issue.severity}">
                  <span class="issue-icon">${issue.severity === 'breaking' ? '✗' : '⚠'}</span>
                  <div class="issue-content">
                    <div class="issue-path">${escapeHtml(issue.path)}</div>
                    <div class="issue-message">${escapeHtml(issue.message)}</div>
                    ${issue.expected && issue.actual ? `
                      <div class="issue-types">
                        <span class="type-badge type-expected">Expected: ${escapeHtml(issue.expected)}</span>
                        <span class="type-separator">→</span>
                        <span class="type-badge type-actual">Actual: ${escapeHtml(issue.actual)}</span>
                      </div>
                    ` : ''}
                  </div>
                </div>
              `).join('')}
            </div>
          `).join('')}
        </div>

        <div class="accept-command">
          <strong>Accept command:</strong>
          <code>npx mockifyer-drift-check --accept "${escapeHtml(report.method)} ${getPathFromUrl(report.url)}"</code>
        </div>
      </div>
    </div>
  `;
}

function generateCleanSection(reports: MockDriftReport[]): string {
  return `
    <section class="clean-section">
      <h2>✅ Clean (${reports.length})</h2>
      <div class="clean-list">
        ${reports.map(report => {
          const isSimulated = report.url.includes('localhost') || report.url.includes('127.0.0.1');
          const simulatedBadge = isSimulated ? '<span class="badge badge-simulated">Simulated</span>' : '';
          return `
            <div class="clean-item">
              <span class="method-badge method-${report.method.toLowerCase()}">${escapeHtml(report.method)}</span>
              <span class="clean-url">${escapeHtml(report.url)}</span>
              ${simulatedBadge}
            </div>
          `;
        }).join('')}
      </div>
    </section>
  `;
}

function generateNotCheckedSection(reports: MockDriftReport[]): string {
  return `
    <section class="not-checked-section">
      <h2>ℹ️ Not Checked (${reports.length})</h2>
      <p class="section-note">These endpoints were not checked (e.g., empty live responses for time-sensitive data)</p>
      <div class="status-list">
        ${reports.map(report => `
          <div class="status-item">
            <span class="method-badge method-${report.method.toLowerCase()}">${escapeHtml(report.method)}</span>
            <span class="status-url">${escapeHtml(report.url)}</span>
            <span class="status-reason">${escapeHtml(report.notCheckedReason || 'Not checked')}</span>
          </div>
        `).join('')}
      </div>
    </section>
  `;
}

function generateSkippedSection(reports: MockDriftReport[]): string {
  return `
    <section class="skipped-section">
      <h2>⊘ Skipped (${reports.length})</h2>
      <p class="section-note">These endpoints were skipped due to errors (e.g., network failures, timeouts)</p>
      <div class="status-list">
        ${reports.map(report => `
          <div class="status-item">
            <span class="method-badge method-${report.method.toLowerCase()}">${escapeHtml(report.method)}</span>
            <span class="status-url">${escapeHtml(report.url)}</span>
            <span class="status-reason">${escapeHtml(report.skipReason || 'Skipped')}</span>
          </div>
        `).join('')}
      </div>
    </section>
  `;
}

function getIssueTypeLabel(type: string): string {
  switch (type) {
    case 'status_change':
      return 'HTTP Status Changed';
    case 'missing_key':
      return 'Fields Removed';
    case 'extra_key':
      return 'Fields Added';
    case 'type_change':
      return 'Types Changed';
    default:
      return 'Other Changes';
  }
}

function getPathFromUrl(url: string): string {
  try {
    const parsed = new URL(url);
    return parsed.pathname + parsed.search;
  } catch {
    return url;
  }
}

function formatTimestamp(iso: string): string {
  try {
    const date = new Date(iso);
    return date.toLocaleString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      timeZoneName: 'short',
    });
  } catch {
    return iso;
  }
}

function escapeHtml(value: unknown): string {
  const s = value == null ? '' : String(value);
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

