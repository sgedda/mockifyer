type InputMode = 'pick' | 'custom'

function clampInt(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return min
  return Math.min(max, Math.max(min, Math.trunc(value)))
}

const DEFAULT_PRESET = simplePreset(DEFAULT_SIMPLE_TYPE_ID)
const DEFAULT_SAMPLE_JSON = presetSampleJson(DEFAULT_PRESET)
const DEFAULT_CONTEXT = DEFAULT_PRESET.context
const DEFAULT_SIZE = resolveSimpleGenerateOptions(DEFAULT_PRESET.sample, DEFAULT_SIMPLE_COUNT)

function parseSampleJson(text: string): { ok: true; value: unknown } | { ok: false; error: string } {
  try {
    return { ok: true, value: JSON.parse(text) as unknown }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    return { ok: false, error: message }
  }
}

export default function MockDataGenerator() {
  const { toast } = useToast()
  const { setTheme } = useTheme()
  const fileInputRef = useRef<HTMLInputElement>(null)
  const shareHydrated = useRef(false)
  const autoGenerated = useRef(false)

  const [mode, setMode] = useState<InputMode>('pick')
  const [typeId, setTypeId] = useState<PlaygroundPresetId>(DEFAULT_SIMPLE_TYPE_ID)
  const [objectCount, setObjectCount] = useState<SimpleObjectCount>(DEFAULT_SIMPLE_COUNT)
  const [inputText, setInputText] = useState(DEFAULT_SAMPLE_JSON)
  const [context, setContext] = useState(DEFAULT_CONTEXT)
  const [locale, setLocale] = useState<PlaygroundLocaleId>(
    localeFromContext(DEFAULT_CONTEXT) || DEFAULT_PLAYGROUND_LOCALE
  )
  const [count, setCount] = useState(DEFAULT_SIZE.count)
  const [itemCount, setItemCount] = useState(DEFAULT_SIZE.itemCount ?? DEFAULT_ITEM_COUNT)
  const [seed, setSeed] = useState<number | string>(DEFAULT_SEED)
  const [seedLocked, setSeedLocked] = useState(false)
  const [level] = useState<PlaygroundChaosLevel>('wild')
  const [overrides, setOverrides] = useState<Record<string, string>>({})
  const [displayOutput, setDisplayOutput] = useState<unknown | null>(null)
  const [namedVariants, setNamedVariants] = useState<NamedVariant[]>([])
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [shareTooLarge, setShareTooLarge] = useState(false)
  const [engineReady, setEngineReady] = useState(false)
  const [bootstrapped, setBootstrapped] = useState(false)
  const [typesLanguage, setTypesLanguage] = useState<TypesLanguage>(DEFAULT_TYPES_LANGUAGE)
  const [moreOpen, setMoreOpen] = useState(false)
  const [outputStatus, setOutputStatus] = useState<string | null>(null)
  const [focusPulse, setFocusPulse] = useState(false)
  const [outputFlash, setOutputFlash] = useState(false)
  const toolWorkspaceRef = useRef<HTMLDivElement>(null)
  const resultsRef = useRef<HTMLDivElement>(null)
  const focusPulseTimer = useRef<ReturnType<typeof setTimeout> | null>(null)
  const outputFlashTimer = useRef<ReturnType<typeof setTimeout> | null>(null)

  useEffect(() => {
    setTheme('light')
  }, [setTheme])

  useEffect(() => {
    return () => {
      if (focusPulseTimer.current) clearTimeout(focusPulseTimer.current)
      if (outputFlashTimer.current) clearTimeout(outputFlashTimer.current)
    }
  }, [])

  const outputNoun = useCallback(
    (count: number) => {
      if (mode === 'pick') {
        const label = SIMPLE_TYPES.find((item) => item.id === typeId)?.label ?? 'records'
        if (count === 1) {
          return label.endsWith('s') ? label.slice(0, -1).toLowerCase() : label.toLowerCase()
        }
        return label.toLowerCase()
      }
      return count === 1 ? 'record' : 'records'
    },
    [mode, typeId]
  )

  /** Prefer how-many / entity count over root wrapper length (`{ users: […] }` → 1). */
  const visibleEntityCount = useCallback(
    (recordCount: number) => {
      if (mode === 'pick') return objectCount
      return recordCount
    },
    [mode, objectCount]
  )

  /** Feedback on the output pane after generate / sample load. */
  const announceOutput = useCallback(
    (opts: {
      recordCount: number
      seedValue: number | string
      fromSample?: boolean
      scroll?: boolean
    }) => {
      const count = visibleEntityCount(opts.recordCount)
      const noun = outputNoun(count)
      const time = new Date().toLocaleTimeString([], {
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
      })
      const lead = opts.fromSample
        ? `Generated ${count} ${noun} from your sample`
        : `Updated · ${count} ${noun}`
      setOutputStatus(`${lead} · seed ${opts.seedValue} · ${time}`)
      setFocusPulse(true)
      setOutputFlash(true)
      if (focusPulseTimer.current) clearTimeout(focusPulseTimer.current)
      if (outputFlashTimer.current) clearTimeout(outputFlashTimer.current)
      focusPulseTimer.current = setTimeout(() => setFocusPulse(false), 2000)
      outputFlashTimer.current = setTimeout(() => setOutputFlash(false), 700)
      if (opts.scroll !== false) {
        requestAnimationFrame(() => {
          const target = resultsRef.current ?? toolWorkspaceRef.current
          target?.scrollIntoView({ behavior: 'smooth', block: 'nearest' })
        })
      }
    },
    [outputNoun, visibleEntityCount]
  )

  const revealToolAfterSample = useCallback(
    (recordCount: number, seedValue: number | string) => {
      setMoreOpen(false)
      announceOutput({
        recordCount,
        seedValue,
        fromSample: true,
        scroll: true,
      })
      requestAnimationFrame(() => {
        toolWorkspaceRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' })
      })
    },
    [announceOutput]
  )

  useEffect(() => {
    if (shareHydrated.current) return
    shareHydrated.current = true
    const state = decodeShareHash(window.location.hash)
    if (state) {
      setInputText(state.input)
      setContext(state.context)
      setLocale(localeFromContext(state.context))
      setCount(clampInt(state.count, MIN_RECORDS, MAX_RECORDS))
      if (typeof state.itemCount === 'number') {
        setItemCount(clampInt(state.itemCount, MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST))
        setObjectCount(clampToSimpleObjectCount(state.itemCount))
      } else {
        setObjectCount(clampToSimpleObjectCount(state.count))
      }
      setSeed(state.seed)
      if (state.overrides) setOverrides(state.overrides)
      if (state.typesLanguage) setTypesLanguage(state.typesLanguage)
      const matched = PLAYGROUND_PRESETS.find(
        (preset) => presetSampleJson(preset).trim() === state.input.trim()
      )
      if (matched && SIMPLE_TYPES.some((t) => t.id === matched.id)) {
        setTypeId(matched.id)
        setMode('pick')
      } else {
        setMode('custom')
      }
    }
    setBootstrapped(true)
  }, [])

  useEffect(() => {
    if (!shareHydrated.current) return
    const result = encodeShareHash({
      input: inputText,
      context,
      seed,
      count,
      itemCount,
      level,
      checked: [],
      overrides,
      typesLanguage,
    })
    if (!result.ok) {
      setShareTooLarge(true)
      return
    }
    setShareTooLarge(false)
    if (window.location.hash !== result.hash) {
      window.history.replaceState(null, '', `${window.location.pathname}${result.hash}`)
    }
  }, [inputText, context, seed, count, itemCount, level, overrides, typesLanguage])

  const runGenerate = useCallback(
    async (opts: {
      sample: unknown
      contextText: string
      localeCode: PlaygroundLocaleId
      kindOverrides: Record<string, string>
      count: number
      itemCount?: number
      seedValue: number | string
      silent?: boolean
    }): Promise<number | null> => {
      setError(null)
      setBusy(true)
      try {
        const engine = await loadGeneratorEngine()
        setEngineReady(true)
        const generated = await engine.generateAsync(opts.sample, {
          seed: opts.seedValue,
          count: opts.count,
          itemCount: opts.itemCount,
          context: opts.contextText.trim() || undefined,
          locale: opts.localeCode,
          overrides: opts.kindOverrides,
        })
        setDisplayOutput(formatSimpleOutput(generated))

        const variants = engine.variants(opts.sample, {
          seed: opts.seedValue,
          chaosLevel: level,
        })
        setNamedVariants(variants)

        if (!opts.silent) {
          toast({
            title: 'Generated',
            description: `${generated.length} record(s)`,
          })
        }
        return generated.length
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err)
        setError(message)
        return null
      } finally {
        setBusy(false)
      }
    },
    [level, toast]
  )

  const generateFromSimple = useCallback(
    async (opts: {
      typeId: PlaygroundPresetId
      objectCount: number
      seedValue: number | string
      localeCode: PlaygroundLocaleId
      itemCountValue?: number
      silent?: boolean
    }): Promise<number | null> => {
      const preset = simplePreset(opts.typeId)
      const size = resolveSimpleGenerateOptions(preset.sample, opts.objectCount)
      const nextItemCount = opts.itemCountValue ?? size.itemCount
      setInputText(presetSampleJson(preset))
      setContext(preset.context)
      setCount(size.count)
      if (typeof nextItemCount === 'number') {
        setItemCount(nextItemCount)
      } else if (typeof size.itemCount === 'number') {
        setItemCount(size.itemCount)
      }
      setOverrides({})
      return runGenerate({
        sample: preset.sample,
        contextText: preset.context,
        localeCode: opts.localeCode,
        kindOverrides: {},
        count: size.count,
        itemCount: nextItemCount ?? size.itemCount,
        seedValue: opts.seedValue,
        silent: opts.silent,
      })
    },
    [runGenerate]
  )

  const generateFromCustom = useCallback(
    async (opts?: {
      silent?: boolean
      seedValue?: number | string
    }): Promise<number | null> => {
      const parsed = parseSampleJson(inputText)
      if (!parsed.ok) {
        setError(`Invalid JSON: ${parsed.error}`)
        return null
      }
      return runGenerate({
        sample: parsed.value,
        contextText: context,
        localeCode: locale,
        kindOverrides: overrides,
        count: objectCount,
        itemCount,
        seedValue: opts?.seedValue ?? seed,
        silent: opts?.silent,
      })
    },
    [inputText, context, locale, overrides, objectCount, itemCount, seed, runGenerate]
  )

  useEffect(() => {
    if (!bootstrapped || autoGenerated.current) return
    autoGenerated.current = true
    if (mode === 'pick') {
      void generateFromSimple({
        typeId,
        objectCount,
        seedValue: seed,
        localeCode: locale,
        itemCountValue: itemCount,
        silent: true,
      })
    } else {
      void generateFromCustom({ silent: true })
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- one-shot after hydrate
  }, [bootstrapped])

  const onSimpleType = (nextId: PlaygroundPresetId) => {
    setTypeId(nextId)
    void generateFromSimple({
      typeId: nextId,
      objectCount,
      seedValue: seed,
      localeCode: locale,
      itemCountValue: itemCount,
      silent: true,
    }).then((count) => {
      if (count != null) announceOutput({ recordCount: count, seedValue: seed, scroll: false })
    })
  }

  const onSimpleCount = (next: SimpleObjectCount) => {
    setObjectCount(next)
    setCount(next)
    if (mode === 'pick') {
      void generateFromSimple({
        typeId,
        objectCount: next,
        seedValue: seed,
        localeCode: locale,
        itemCountValue: itemCount,
        silent: true,
      }).then((count) => {
        if (count != null) announceOutput({ recordCount: count, seedValue: seed, scroll: false })
      })
      return
    }
    const parsed = parseSampleJson(inputText)
    if (!parsed.ok) {
      setError(`Invalid JSON: ${parsed.error}`)
      return
    }
    void runGenerate({
      sample: parsed.value,
      contextText: context,
      localeCode: locale,
      kindOverrides: overrides,
      count: next,
      itemCount,
      seedValue: seed,
      silent: true,
    }).then((count) => {
      if (count != null) announceOutput({ recordCount: count, seedValue: seed, scroll: false })
    })
  }

  const onLocaleChange = (next: PlaygroundLocaleId) => {
    setLocale(next)
    if (mode === 'pick') {
      void generateFromSimple({
        typeId,
        objectCount,
        seedValue: seed,
        localeCode: next,
        itemCountValue: itemCount,
      })
      return
    }
    const parsed = parseSampleJson(inputText)
    if (!parsed.ok) {
      setError(`Invalid JSON: ${parsed.error}`)
      return
    }
    void runGenerate({
      sample: parsed.value,
      contextText: context,
      localeCode: next,
      kindOverrides: overrides,
      count: objectCount,
      itemCount,
      seedValue: seed,
    })
  }

  const onItemCountChange = (next: number) => {
    const clamped = clampInt(next, MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST)
    setItemCount(clamped)
    if (mode === 'pick') {
      void generateFromSimple({
        typeId,
        objectCount,
        seedValue: seed,
        localeCode: locale,
        itemCountValue: clamped,
      })
      return
    }
    const parsed = parseSampleJson(inputText)
    if (!parsed.ok) {
      setError(`Invalid JSON: ${parsed.error}`)
      return
    }
    void runGenerate({
      sample: parsed.value,
      contextText: context,
      localeCode: locale,
      kindOverrides: overrides,
      count: objectCount,
      itemCount: clamped,
      seedValue: seed,
    })
  }

  /** Single primary action: new seed (unless locked) → regenerate → flash output. */
  const onGenerate = () => {
    const nextSeed = seedLocked ? seed : newRandomSeed()
    if (!seedLocked) setSeed(nextSeed)
    const finish = (recordCount: number | null | undefined) => {
      if (recordCount == null) return
      announceOutput({ recordCount, seedValue: nextSeed, scroll: true })
    }
    if (mode === 'pick') {
      void generateFromSimple({
        typeId,
        objectCount,
        seedValue: nextSeed,
        localeCode: locale,
        itemCountValue: itemCount,
        silent: true,
      }).then((count) => finish(count ?? null))
    } else {
      void generateFromCustom({ seedValue: nextSeed, silent: true }).then((count) =>
        finish(count ?? null)
      )
    }
  }

  const handlePreset = async (
    preset: PlaygroundPreset,
    opts?: { reveal?: boolean }
  ): Promise<number | null> => {
    if (SIMPLE_TYPES.some((t) => t.id === preset.id)) {
      setTypeId(preset.id)
    }
    setInputText(presetSampleJson(preset))
    setContext(preset.context)
    setLocale(localeFromContext(preset.context))
    setOverrides({})
    const size = resolveSimpleGenerateOptions(preset.sample, objectCount)
    setCount(size.count)
    if (typeof size.itemCount === 'number') setItemCount(size.itemCount)
    const recordCount = await runGenerate({
      sample: preset.sample,
      contextText: preset.context,
      localeCode: localeFromContext(preset.context),
      kindOverrides: {},
      count: size.count,
      itemCount: size.itemCount,
      seedValue: seed,
      silent: opts?.reveal,
    })
    if (opts?.reveal && recordCount != null) {
      revealToolAfterSample(recordCount, seed)
    }
    return recordCount
  }

  const handleUseRealApiSample = async (example: RealApiExample) => {
    setMode('custom')
    const preset = example.preset
    if (preset) {
      await handlePreset(preset, { reveal: true })
      return
    }
    setInputText(`${JSON.stringify(example.recorded, null, 2)}\n`)
    setContext(example.context)
    setLocale(localeFromContext(example.context))
    setOverrides({})
    const size = resolveSimpleGenerateOptions(example.recorded, objectCount)
    setCount(size.count)
    if (typeof size.itemCount === 'number') setItemCount(size.itemCount)
    const recordCount = await runGenerate({
      sample: example.recorded,
      contextText: example.context,
      localeCode: localeFromContext(example.context),
      kindOverrides: {},
      count: size.count,
      itemCount: size.itemCount ?? itemCount,
      seedValue: seed,
      silent: true,
    })
    if (recordCount != null) {
      revealToolAfterSample(recordCount, seed)
    }
  }

  const handleUpload = async (file: File | null) => {
    if (!file) return
    try {
      const text = await file.text()
      const parsed = parseSampleJson(text)
      if (!parsed.ok) {
        throw new Error(parsed.error)
      }
      setMode('custom')
      setInputText(text.endsWith('\n') ? text : `${text}\n`)
      const size = resolveSimpleGenerateOptions(parsed.value, objectCount)
      setCount(size.count)
      if (typeof size.itemCount === 'number') setItemCount(size.itemCount)
      const recordCount = await runGenerate({
        sample: parsed.value,
        contextText: context,
        localeCode: locale,
        kindOverrides: overrides,
        count: size.count,
        itemCount: size.itemCount ?? itemCount,
        seedValue: seed,
        silent: true,
      })
      if (recordCount != null) {
        revealToolAfterSample(recordCount, seed)
      }
      toast({ title: 'Sample loaded', description: file.name })
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      toast({ title: 'Invalid JSON file', description: message, variant: 'destructive' })
    }
  }

  const handleDownloadRecords = () => {
    if (displayOutput == null) return
    downloadJsonText(`${JSON.stringify(displayOutput, null, 2)}\n`, 'mockifyer-generated.json')
  }

  const handleDownloadVariantsZip = async () => {
    if (namedVariants.length === 0) return
    await downloadVariantMocksZip(namedVariants)
    toast({
      title: 'Downloaded mock files',
      description: "Ready to drop into your project's mock-data folder.",
    })
  }

  const handleCopyShareLink = async () => {
    if (shareTooLarge) {
      toast({
        title: 'Input too large for a URL',
        description: 'Shrink the sample JSON, then try again.',
        variant: 'destructive',
      })
      return
    }
    await navigator.clipboard.writeText(window.location.href)
    toast({ title: 'Share link copied' })
  }

  const localeLabel = useMemo(
    () => PLAYGROUND_LOCALES.find((item) => item.id === locale)?.label ?? 'English (US)',
    [locale]
  )

  return (
    <div
      className="bg-white text-zinc-950 overflow-x-hidden"
      data-testid="mock-data-generator-page"
    >
      <div className="mx-auto max-w-[1200px] px-4 sm:px-5 py-6 sm:py-10 space-y-6">
        <header className="space-y-2" data-testid="playground-intro">
          <h1 className="text-2xl sm:text-3xl font-semibold tracking-tight flex items-center gap-2">
            <Wand2 className="h-7 w-7 text-primary shrink-0" />
            Free Mock Data Generator
          </h1>
          <div className="flex flex-wrap items-center gap-2 text-sm">
            <span
              className="inline-flex items-center gap-1.5 rounded-md border border-emerald-200 bg-emerald-50 px-2.5 py-1 text-emerald-800 w-fit"
              data-testid="privacy-note"
            >
              <Shield className="h-3.5 w-3.5 shrink-0" />
              Nothing leaves your browser
            </span>
            <span className="text-muted-foreground text-xs sm:text-sm">
              Pick a type or paste your own JSON
              {engineReady ? ' · engine loaded' : ''}.
            </span>
          </div>
        </header>

        <div
          ref={toolWorkspaceRef}
          id="tool-workspace"
          data-testid="tool-workspace"
          className="scroll-mt-4 space-y-4"
        >
          {/* Mode switch */}
          <div
            className="inline-flex rounded-lg border border-border p-0.5 bg-muted/40 w-full sm:w-fit"
            role="tablist"
            aria-label="How to start"
            data-testid="input-mode-switch"
          >
            <button
              type="button"
              role="tab"
              aria-selected={mode === 'pick'}
              data-testid="mode-pick"
              className={`flex-1 sm:flex-none px-4 py-2.5 text-sm font-semibold rounded-md min-h-11 ${
                mode === 'pick'
                  ? 'bg-background text-foreground shadow-sm'
                  : 'text-muted-foreground'
              }`}
              onClick={() => setMode('pick')}
            >
              Pick a type
            </button>
            <button
              type="button"
              role="tab"
              aria-selected={mode === 'custom'}
              data-testid="mode-custom"
              className={`flex-1 sm:flex-none px-4 py-2.5 text-sm font-semibold rounded-md min-h-11 ${
                mode === 'custom'
                  ? 'bg-background text-foreground shadow-sm'
                  : 'text-muted-foreground'
              }`}
              onClick={() => setMode('custom')}
            >
              Use my own JSON
            </button>
          </div>

          {/* One tool card: controls → Generate → result */}
          <section
            className={cn(
              'rounded-xl border border-border bg-zinc-50/60 overflow-hidden',
              focusPulse && 'mdg-focus-pulse'
            )}
            data-testid="tool-card"
          >
            {mode === 'pick' ? (
              <div
                className="p-3 sm:p-4 border-b border-border space-y-4"
                data-testid="simple-controls"
              >
                <div className="flex flex-col gap-3 sm:flex-row sm:flex-wrap sm:items-end">
                  <div className="space-y-1.5 min-w-0 flex-1 sm:flex-none sm:min-w-[180px]">
                    <Label htmlFor="simple-type" className="text-sm font-semibold">
                      Type
                    </Label>
                    <p className="text-xs text-muted-foreground">What kind of fake data?</p>
                    <Select
                      value={typeId}
                      onValueChange={(value) => onSimpleType(value as PlaygroundPresetId)}
                      disabled={busy && !displayOutput}
                    >
                      <SelectTrigger
                        id="simple-type"
                        className="min-h-11 w-full sm:w-[200px] bg-white"
                        data-testid="simple-type-select"
                      >
                        <SelectValue />
                      </SelectTrigger>
                      <SelectContent>
                        {SIMPLE_TYPES.map((item) => (
                          <SelectItem
                            key={item.id}
                            value={item.id}
                            data-testid={`simple-type-${item.id}`}
                          >
                            {item.label}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </div>

                  <div className="space-y-1.5" data-testid="simple-object-count">
                    <Label className="text-sm font-semibold">How many</Label>
                    <p className="text-xs text-muted-foreground">Number of objects</p>
                    <div
                      className="flex flex-wrap gap-1.5"
                      role="group"
                      aria-label="Number of objects"
                    >
                      {SIMPLE_OBJECT_COUNTS.map((n) => (
                        <Button
                          key={n}
                          type="button"
                          size="sm"
                          variant={n === objectCount ? 'default' : 'outline'}
                          className="min-h-11 min-w-11"
                          data-testid={`simple-count-${n}`}
                          disabled={busy && !displayOutput}
                          onClick={() => onSimpleCount(n)}
                        >
                          {n}
                        </Button>
                      ))}
                    </div>
                  </div>
                </div>
              </div>
            ) : null}

            <div
              className="p-3 sm:p-4 border-b border-border"
              data-testid="customize-row"
            >
              <p className="text-sm font-semibold mb-3">Customize</p>
              <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
                <div className="space-y-1.5" data-testid="locale-control">
                  <Label htmlFor="locale-select" className="text-sm font-medium">
                    Locale
                  </Label>
                  <p className="text-xs text-muted-foreground">Names, phones, currency style</p>
                  <Select
                    value={locale}
                    onValueChange={(value) => onLocaleChange(parsePlaygroundLocale(value))}
                  >
                    <SelectTrigger
                      id="locale-select"
                      className="min-h-11 bg-white"
                      data-testid="locale-select"
                    >
                      <SelectValue>
                        {PLAYGROUND_LOCALES.find((item) => item.id === locale)?.flag}{' '}
                        {localeLabel}
                      </SelectValue>
                    </SelectTrigger>
                    <SelectContent>
                      {PLAYGROUND_LOCALES.map((item) => (
                        <SelectItem
                          key={item.id}
                          value={item.id}
                          data-testid={`locale-${item.id}`}
                        >
                          {item.flag} {item.label}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>

                <div className="space-y-1.5" data-testid="items-per-list-control">
                  <Label htmlFor="item-count" className="text-sm font-medium">
                    Items per list
                  </Label>
                  <p className="text-xs text-muted-foreground">Length of nested arrays</p>
                  <div className="flex items-center gap-2">
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="Fewer items per list"
                      data-testid="item-count-decrement"
                      disabled={busy || itemCount <= MIN_ITEMS_PER_LIST}
                      onClick={() => onItemCountChange(itemCount - 1)}
                    >
                      <Minus className="h-4 w-4" />
                    </Button>
                    <Input
                      id="item-count"
                      data-testid="item-count-input"
                      type="number"
                      min={MIN_ITEMS_PER_LIST}
                      max={MAX_ITEMS_PER_LIST}
                      className="min-h-11 text-center text-base font-semibold bg-white"
                      value={itemCount}
                      onChange={(e) => onItemCountChange(Number(e.target.value))}
                    />
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="More items per list"
                      data-testid="item-count-increment"
                      disabled={busy || itemCount >= MAX_ITEMS_PER_LIST}
                      onClick={() => onItemCountChange(itemCount + 1)}
                    >
                      <Plus className="h-4 w-4" />
                    </Button>
                  </div>
                </div>

                <div className="space-y-1.5" data-testid="seed-control">
                  <Label htmlFor="seed-input" className="text-sm font-medium">
                    Seed
                  </Label>
                  <p className="text-xs text-muted-foreground">
                    Same seed → same data. Lock to keep it.
                  </p>
                  <div className="flex items-center gap-2">
                    <Input
                      id="seed-input"
                      data-testid="seed-input"
                      className="min-h-11 bg-white"
                      value={String(seed)}
                      disabled={seedLocked}
                      onChange={(e) => {
                        const raw = e.target.value
                        setSeed(/^-?\d+$/.test(raw) ? Number(raw) : raw)
                      }}
                    />
                    <Button
                      type="button"
                      variant={seedLocked ? 'default' : 'outline'}
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label={seedLocked ? 'Unlock seed' : 'Lock seed'}
                      data-testid="seed-lock-toggle"
                      onClick={() => setSeedLocked((prev) => !prev)}
                    >
                      {seedLocked ? <Lock className="h-4 w-4" /> : <Unlock className="h-4 w-4" />}
                    </Button>
                  </div>
                </div>
              </div>
            </div>

            <div
              ref={resultsRef}
              className={cn(
                'p-3 sm:p-4 space-y-3 bg-white scroll-mt-4',
                outputFlash && 'mdg-output-flash'
              )}
              data-testid="results-section"
            >
              {mode === 'custom' ? (
                <div
                  className="grid grid-cols-1 lg:grid-cols-2 gap-4"
                  data-testid="custom-workspace"
                >
                  <div
                    className={cn(
                      'space-y-3 rounded-lg border border-border p-3',
                      focusPulse && 'mdg-pane-pulse'
                    )}
                    data-testid="custom-json-section"
                  >
                    <div className="space-y-1.5">
                      <Label htmlFor="sample-json" className="text-sm font-semibold">
                        Your sample JSON
                      </Label>
                      <p className="text-xs text-muted-foreground">
                        Paste a response — Generate creates more records with the same shape.
                      </p>
                      <Textarea
                        id="sample-json"
                        data-testid="sample-json"
                        className="min-h-[180px] max-h-[360px] font-mono text-xs sm:text-sm bg-zinc-50"
                        value={inputText}
                        onChange={(e) => setInputText(e.target.value)}
                        spellCheck={false}
                      />
                    </div>
                    <div className="flex flex-wrap gap-2">
                      <input
                        ref={fileInputRef}
                        type="file"
                        accept="application/json,.json"
                        className="hidden"
                        onChange={(e) => void handleUpload(e.target.files?.[0] ?? null)}
                      />
                      <Button
                        type="button"
                        variant="outline"
                        className="min-h-11"
                        data-testid="upload-json-button"
                        onClick={() => fileInputRef.current?.click()}
                      >
                        <Upload className="h-4 w-4 mr-2" />
                        Upload JSON
                      </Button>
                    </div>
                  </div>

                  <div
                    className={cn('space-y-3 min-w-0', focusPulse && 'mdg-pane-pulse')}
                    data-testid="custom-output-pane"
                  >
                    <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                      <div className="min-w-0">
                        <h2 className="text-base font-semibold tracking-tight">Generated output</h2>
                        {outputStatus ? (
                          <p
                            className="text-xs text-muted-foreground truncate"
                            data-testid="output-status"
                            aria-live="polite"
                          >
                            {outputStatus}
                          </p>
                        ) : (
                          <p className="text-xs text-muted-foreground">
                            Results appear here next to your sample.
                          </p>
                        )}
                      </div>
                      <Button
                        type="button"
                        className="min-h-11 w-full sm:w-auto shrink-0"
                        data-testid="generate-button"
                        disabled={busy}
                        onClick={onGenerate}
                      >
                        {busy ? (
                          <Loader2 className="h-4 w-4 mr-2 animate-spin" />
                        ) : (
                          <Dices className="h-4 w-4 mr-2" />
                        )}
                        Generate
                      </Button>
                    </div>
                    <GeneratedOutputPanel
                      output={displayOutput}
                      busy={busy}
                      error={error}
                      testIdPrefix="tool"
                      rootTypeName="Root"
                      typesLanguage={typesLanguage}
                      onTypesLanguageChange={setTypesLanguage}
                      preClassName="max-h-[min(360px,45vh)] overflow-auto p-3 sm:p-4 text-xs font-mono whitespace-pre-wrap break-all leading-relaxed"
                      onCopied={(tab) => {
                        toast({ title: tab === 'json' ? 'JSON copied' : 'Types copied' })
                      }}
                      extraActions={
                        <Button
                          type="button"
                          variant="outline"
                          size="sm"
                          className="min-h-9"
                          data-testid="download-json"
                          disabled={displayOutput == null}
                          onClick={handleDownloadRecords}
                        >
                          <Download className="h-3.5 w-3.5 mr-1.5" />
                          Download
                        </Button>
                      }
                    />
                  </div>
                </div>
              ) : (
                <div className="space-y-3">
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                    <div className="min-w-0">
                      <h2 className="text-base font-semibold tracking-tight">Generated output</h2>
                      {outputStatus ? (
                        <p
                          className="text-xs text-muted-foreground truncate"
                          data-testid="output-status"
                          aria-live="polite"
                        >
                          {outputStatus}
                        </p>
                      ) : (
                        <p className="text-xs text-muted-foreground">
                          Press Generate to refresh values (new seed unless locked).
                        </p>
                      )}
                    </div>
                    <Button
                      type="button"
                      className="min-h-11 w-full sm:w-auto shrink-0"
                      data-testid="generate-button"
                      disabled={busy && !displayOutput}
                      onClick={onGenerate}
                    >
                      {busy && displayOutput ? (
                        <Loader2 className="h-4 w-4 mr-2 animate-spin" />
                      ) : (
                        <Dices className="h-4 w-4 mr-2" />
                      )}
                      Generate
                    </Button>
                  </div>
                  <GeneratedOutputPanel
                    output={displayOutput}
                    busy={busy}
                    error={error}
                    testIdPrefix="tool"
                    rootTypeName="Root"
                    typesLanguage={typesLanguage}
                    onTypesLanguageChange={setTypesLanguage}
                    preClassName="max-h-[min(420px,50vh)] overflow-auto p-3 sm:p-4 text-xs font-mono whitespace-pre-wrap break-all leading-relaxed"
                    onCopied={(tab) => {
                      toast({ title: tab === 'json' ? 'JSON copied' : 'Types copied' })
                    }}
                    extraActions={
                      <Button
                        type="button"
                        variant="outline"
                        size="sm"
                        className="min-h-9"
                        data-testid="download-json"
                        disabled={displayOutput == null}
                        onClick={handleDownloadRecords}
                      >
                        <Download className="h-3.5 w-3.5 mr-1.5" />
                        Download
                      </Button>
                    }
                  />
                </div>
              )}
            </div>
          </section>
        </div>

        {/* More — share, ZIP, real API, record */}
        <details
          className="group rounded-xl border border-border"
          data-testid="more-section"
          open={moreOpen}
          onToggle={(e) => setMoreOpen((e.target as HTMLDetailsElement).open)}
        >
          <summary className="cursor-pointer list-none flex items-center justify-between gap-3 px-4 py-3 sm:px-5 min-h-12 select-none">
            <span className="font-semibold text-base">More</span>
            <span className="text-xs text-muted-foreground hidden sm:inline">
              Share link · mock files · real API example · record
            </span>
            <ChevronDown className="h-4 w-4 text-muted-foreground transition-transform group-open:rotate-180" />
          </summary>
          <div className="border-t border-border px-4 sm:px-5 py-5 space-y-6">
            <div className="flex flex-col sm:flex-row flex-wrap gap-2">
              <Button
                type="button"
                variant="outline"
                className="min-h-11"
                data-testid="copy-share-link"
                onClick={() => void handleCopyShareLink()}
              >
                <Link2 className="h-4 w-4 mr-2" />
                Copy share link
              </Button>
              <Button
                type="button"
                variant="outline"
                className="min-h-11"
                data-testid="download-variants-zip"
                disabled={namedVariants.length === 0}
                onClick={() => void handleDownloadVariantsZip()}
              >
                <FileJson className="h-4 w-4 mr-2" />
                Download mock files (ZIP)
              </Button>
            </div>
            {shareTooLarge ? (
              <p
                className="text-sm text-amber-800 bg-amber-50 border border-amber-200 rounded-md px-3 py-2"
                data-testid="share-too-large"
              >
                This sample is too large to fit in a shareable URL.
              </p>
            ) : null}

            <RealApiDemo onUseAsSample={(example) => void handleUseRealApiSample(example)} />

            <section
              className="border border-border rounded-xl bg-zinc-50/80 px-6 py-8 sm:px-10 space-y-4"
              data-testid="record-cta"
            >
              <div className="flex items-start gap-3">
                <Radio className="h-7 w-7 text-primary shrink-0 mt-1" aria-hidden />
                <div className="space-y-2 max-w-3xl">
                  <h2 className="text-xl sm:text-2xl font-semibold tracking-tight">
                    Got a real API? Record it with Mockifyer
                  </h2>
                  <p className="text-muted-foreground text-sm sm:text-base">
                    Capture live responses once, then replay them offline.
                  </p>
                </div>
              </div>
              <div className="flex flex-wrap items-center gap-4">
                <Button asChild data-testid="record-cta-getting-started">
                  <Link to="/getting-started">
                    Start recording
                    <ArrowRight className="h-4 w-4 ml-2" />
                  </Link>
                </Button>
                <button
                  type="button"
                  className="text-sm text-primary underline-offset-4 hover:underline font-medium"
                  data-testid="record-cta-try-demo"
                  onClick={() => {
                    void navigator.clipboard.writeText(TRY_DEMO_COMMAND).then(() => {
                      toast({
                        title: 'Copied try command',
                        description: TRY_DEMO_COMMAND,
                      })
                    })
                  }}
                >
                  Or try the demo:{' '}
                  <code className="text-xs bg-white border px-1.5 py-0.5 rounded">
                    {TRY_DEMO_COMMAND}
                  </code>
                </button>
              </div>
            </section>
          </div>
        </details>

        <MockDataGeneratorSeo />
      </div>
    </div>
  )
}
