function clampInt(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return min
  return Math.min(max, Math.max(min, Math.trunc(value)))
}

const DEFAULT_PRESET = simplePreset(DEFAULT_SIMPLE_TYPE_ID)
const DEFAULT_SAMPLE_JSON = presetSampleJson(DEFAULT_PRESET)
const DEFAULT_CONTEXT = DEFAULT_PRESET.context
const DEFAULT_SIZE = resolveSimpleGenerateOptions(DEFAULT_PRESET.sample, DEFAULT_SIMPLE_COUNT)

function parseSampleJson(text: string): { ok: true; value: unknown } | { ok: false; error: string } {
  try {
    return { ok: true, value: JSON.parse(text) as unknown }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    return { ok: false, error: message }
  }
}

function variantLabel(kind: string, name: string): string {
  return `${name} (${kind})`
}

export default function MockDataGenerator() {
  const { toast } = useToast()
  const { setTheme } = useTheme()
  const fileInputRef = useRef<HTMLInputElement>(null)
  const shareHydrated = useRef(false)
  const autoGenerated = useRef(false)

  const [typeId, setTypeId] = useState<PlaygroundPresetId>(DEFAULT_SIMPLE_TYPE_ID)
  const [objectCount, setObjectCount] = useState<SimpleObjectCount>(DEFAULT_SIMPLE_COUNT)
  const [inputText, setInputText] = useState(DEFAULT_SAMPLE_JSON)
  const [context, setContext] = useState(DEFAULT_CONTEXT)
  const [count, setCount] = useState(DEFAULT_SIZE.count)
  const [itemCount, setItemCount] = useState(DEFAULT_SIZE.itemCount ?? DEFAULT_ITEM_COUNT)
  const [seed, setSeed] = useState<number | string>(DEFAULT_SEED)
  const [level, setLevel] = useState<PlaygroundChaosLevel>('wild')
  const [fields, setFields] = useState<FieldDescriptor[]>([])
  const [overrides, setOverrides] = useState<Record<string, string>>({})
  const [records, setRecords] = useState<unknown[] | null>(null)
  const [displayOutput, setDisplayOutput] = useState<unknown | null>(null)
  const [namedVariants, setNamedVariants] = useState<NamedVariant[]>([])
  const [checked, setChecked] = useState<Record<string, boolean>>({})
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [shareTooLarge, setShareTooLarge] = useState(false)
  const [engineReady, setEngineReady] = useState(false)
  const [bootstrapped, setBootstrapped] = useState(false)
  const [typesLanguage, setTypesLanguage] = useState<TypesLanguage>(DEFAULT_TYPES_LANGUAGE)

  useEffect(() => {
    setTheme('light')
  }, [setTheme])

  // Hydrate from shareable URL hash once
  useEffect(() => {
    if (shareHydrated.current) return
    shareHydrated.current = true
    const state = decodeShareHash(window.location.hash)
    if (state) {
      setInputText(state.input)
      setContext(state.context)
      setCount(clampInt(state.count, MIN_RECORDS, MAX_RECORDS))
      if (typeof state.itemCount === 'number') {
        setItemCount(clampInt(state.itemCount, MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST))
        setObjectCount(clampToSimpleObjectCount(state.itemCount))
      } else {
        setObjectCount(clampToSimpleObjectCount(state.count))
      }
      setSeed(state.seed)
      setLevel(state.level)
      if (state.overrides) setOverrides(state.overrides)
      if (state.typesLanguage) setTypesLanguage(state.typesLanguage)
      const nextChecked: Record<string, boolean> = {}
      for (const slug of state.checked) {
        nextChecked[slug] = true
      }
      setChecked(nextChecked)
      // Best-effort: match a known simple type from sample JSON
      const matched = PLAYGROUND_PRESETS.find(
        (preset) => presetSampleJson(preset).trim() === state.input.trim()
      )
      if (matched && SIMPLE_TYPES.some((t) => t.id === matched.id)) {
        setTypeId(matched.id)
      }
    }
    setBootstrapped(true)
  }, [])

  // Persist shareable state in the hash
  useEffect(() => {
    if (!shareHydrated.current) return
    const checkedSlugs = Object.entries(checked)
      .filter(([, on]) => on)
      .map(([slug]) => slug)
    const result = encodeShareHash({
      input: inputText,
      context,
      seed,
      count,
      itemCount,
      level,
      checked: checkedSlugs,
      overrides,
      typesLanguage,
    })
    if (!result.ok) {
      setShareTooLarge(true)
      return
    }
    setShareTooLarge(false)
    if (window.location.hash !== result.hash) {
      window.history.replaceState(null, '', `${window.location.pathname}${result.hash}`)
    }
  }, [inputText, context, seed, count, itemCount, level, checked, overrides, typesLanguage])

  const sampleCli = useMemo(
    () => buildSampleCliCommand({ seed, count, context }),
    [seed, count, context]
  )

  const variantsCli = useMemo(
    () => buildVariantsCliCommand({ seed, level }),
    [seed, level]
  )

  const checkedCount = useMemo(
    () => Object.values(checked).filter(Boolean).length,
    [checked]
  )

  const inferKinds = useCallback(async (sample: unknown, nextOverrides: Record<string, string>) => {
    const engine = await loadGeneratorEngine()
    setEngineReady(true)
    const inferred = engine.infer(sample, nextOverrides)
    setFields(inferred.fields)
  }, [])

  useEffect(() => {
    const parsed = parseSampleJson(inputText)
    if (!parsed.ok) {
      setFields([])
      return
    }
    let cancelled = false
    void (async () => {
      try {
        await inferKinds(parsed.value, overrides)
      } catch (err) {
        if (!cancelled) {
          const message = err instanceof Error ? err.message : String(err)
          setError(message)
        }
      }
    })()
    return () => {
      cancelled = true
    }
  }, [inputText, overrides, inferKinds])

  const handleUpload = async (file: File | null) => {
    if (!file) return
    try {
      const text = await file.text()
      parseSampleJson(text)
      setInputText(text.endsWith('\n') ? text : `${text}\n`)
      toast({ title: 'Sample loaded', description: file.name })
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      toast({ title: 'Invalid JSON file', description: message, variant: 'destructive' })
    }
  }

  const runGenerate = useCallback(
    async (opts: {
      sample: unknown
      contextText: string
      kindOverrides: Record<string, string>
      count: number
      itemCount?: number
      seedValue: number | string
      silent?: boolean
    }) => {
      setError(null)
      setBusy(true)
      try {
        const engine = await loadGeneratorEngine()
        setEngineReady(true)
        const generated = await engine.generateAsync(opts.sample, {
          seed: opts.seedValue,
          count: opts.count,
          itemCount: opts.itemCount,
          context: opts.contextText.trim() || undefined,
          overrides: opts.kindOverrides,
        })
        setRecords(generated)
        setDisplayOutput(formatSimpleOutput(generated))

        const variants = engine.variants(opts.sample, {
          seed: opts.seedValue,
          chaosLevel: level,
        })
        setNamedVariants(variants)
        setChecked((prev) => {
          const next: Record<string, boolean> = {}
          for (const v of variants) {
            if (prev[v.name]) next[v.name] = true
          }
          return next
        })

        if (!opts.silent) {
          toast({
            title: 'Generated',
            description: `${generated.length} record(s), ${variants.length} edge-case variant(s)`,
          })
        }
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err)
        setError(message)
      } finally {
        setBusy(false)
      }
    },
    [level, toast]
  )

  const generateFromSimple = useCallback(
    async (opts: {
      typeId: PlaygroundPresetId
      objectCount: number
      seedValue: number | string
      silent?: boolean
    }) => {
      const preset = simplePreset(opts.typeId)
      const size = resolveSimpleGenerateOptions(preset.sample, opts.objectCount)
      setInputText(presetSampleJson(preset))
      setContext(preset.context)
      setCount(size.count)
      if (typeof size.itemCount === 'number') {
        setItemCount(size.itemCount)
      }
      setOverrides({})
      await runGenerate({
        sample: preset.sample,
        contextText: preset.context,
        kindOverrides: {},
        count: size.count,
        itemCount: size.itemCount,
        seedValue: opts.seedValue,
        silent: opts.silent,
      })
    },
    [runGenerate]
  )

  const handleGenerateAdvanced = async (opts?: { silent?: boolean }) => {
    const parsed = parseSampleJson(inputText)
    if (!parsed.ok) {
      setError(`Invalid JSON: ${parsed.error}`)
      return
    }
    await runGenerate({
      sample: parsed.value,
      contextText: context,
      kindOverrides: overrides,
      count,
      itemCount,
      seedValue: seed,
      silent: opts?.silent,
    })
  }

  useEffect(() => {
    if (!bootstrapped || autoGenerated.current) return
    autoGenerated.current = true
    // Share hash already hydrated input — generate from current advanced state if custom,
    // otherwise use simple defaults.
    const matched = PLAYGROUND_PRESETS.find(
      (preset) => presetSampleJson(preset).trim() === inputText.trim()
    )
    if (matched && SIMPLE_TYPES.some((t) => t.id === matched.id)) {
      void generateFromSimple({
        typeId: matched.id,
        objectCount,
        seedValue: seed,
        silent: true,
      })
    } else {
      void handleGenerateAdvanced({ silent: true })
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- one-shot after hydrate
  }, [bootstrapped])

  const onSimpleType = (nextId: PlaygroundPresetId) => {
    setTypeId(nextId)
    void generateFromSimple({ typeId: nextId, objectCount, seedValue: seed })
  }

  const onSimpleCount = (next: SimpleObjectCount) => {
    setObjectCount(next)
    void generateFromSimple({ typeId, objectCount: next, seedValue: seed })
  }

  const onRandomize = () => {
    const nextSeed = newRandomSeed()
    setSeed(nextSeed)
    void generateFromSimple({ typeId, objectCount, seedValue: nextSeed })
  }

  const handlePreset = async (preset: PlaygroundPreset) => {
    if (SIMPLE_TYPES.some((t) => t.id === preset.id)) {
      setTypeId(preset.id)
    }
    setInputText(presetSampleJson(preset))
    setContext(preset.context)
    setOverrides({})
    const size = resolveSimpleGenerateOptions(preset.sample, objectCount)
    setCount(size.count)
    if (typeof size.itemCount === 'number') setItemCount(size.itemCount)
    await runGenerate({
      sample: preset.sample,
      contextText: preset.context,
      kindOverrides: {},
      count: size.count,
      itemCount: size.itemCount,
      seedValue: seed,
    })
  }

  const handleUseRealApiSample = async (example: RealApiExample) => {
    const preset = example.preset
    if (preset) {
      await handlePreset(preset)
      return
    }
    setInputText(`${JSON.stringify(example.recorded, null, 2)}\n`)
    setContext(example.context)
    setOverrides({})
    await runGenerate({
      sample: example.recorded,
      contextText: example.context,
      kindOverrides: {},
      count,
      itemCount,
      seedValue: seed,
    })
  }

  const handleResetExample = () => {
    setTypeId(DEFAULT_SIMPLE_TYPE_ID)
    setObjectCount(DEFAULT_SIMPLE_COUNT)
    setInputText(DEFAULT_SAMPLE_JSON)
    setContext(DEFAULT_CONTEXT)
    setCount(DEFAULT_SIZE.count)
    setItemCount(DEFAULT_SIZE.itemCount ?? DEFAULT_ITEM_COUNT)
    setOverrides({})
  }

  const handleDownloadRecords = () => {
    if (displayOutput == null) return
    downloadJsonText(`${JSON.stringify(displayOutput, null, 2)}\n`, 'mockifyer-generated.json')
  }

  const handleDownloadVariantsZip = async () => {
    if (namedVariants.length === 0) return
    await downloadVariantMocksZip(namedVariants)
    toast({
      title: 'Downloaded mock files',
      description: "Ready to drop into your project's mock-data folder.",
    })
  }

  const handleCopyShareLink = async () => {
    if (shareTooLarge) {
      toast({
        title: 'Input too large for a URL',
        description: 'Shrink the sample JSON, then try again.',
        variant: 'destructive',
      })
      return
    }
    await navigator.clipboard.writeText(window.location.href)
    toast({ title: 'Share link copied' })
  }

  const onOverrideKind = (path: string, kind: string) => {
    setOverrides((prev) => ({ ...prev, [path]: kind }))
  }

  const sliderIndex = CHAOS_LEVEL_INDEX[level]
  const { editable: editableFields, structural: structuralFields } = useMemo(
    () => partitionFieldRows(fields),
    [fields]
  )

  return (
    <div
      className="bg-white text-zinc-950 overflow-x-hidden"
      data-testid="mock-data-generator-page"
    >
      <div className="mx-auto max-w-[1200px] px-4 sm:px-5 py-6 sm:py-10 space-y-6">
        <header className="space-y-2" data-testid="playground-intro">
          <h1 className="text-2xl sm:text-3xl font-semibold tracking-tight flex items-center gap-2">
            <Wand2 className="h-7 w-7 text-primary shrink-0" />
            Mock data generator
          </h1>
          <div className="flex flex-wrap items-center gap-2 text-sm">
            <span
              className="inline-flex items-center gap-1.5 rounded-md border border-emerald-200 bg-emerald-50 px-2.5 py-1 text-emerald-800 w-fit"
              data-testid="privacy-note"
            >
              <Shield className="h-3.5 w-3.5 shrink-0" />
              Nothing leaves your browser
            </span>
            <span className="text-muted-foreground text-xs sm:text-sm">
              Pick a type, set how many, randomize
              {engineReady ? ' · engine loaded' : ''}.
            </span>
          </div>
        </header>

        {/* Simple controls */}
        <section
          className="rounded-xl border border-border bg-zinc-50/80 p-3 sm:p-4 space-y-4"
          data-testid="simple-controls"
        >
          <div className="flex flex-col gap-3 sm:flex-row sm:flex-wrap sm:items-end">
            <div className="space-y-1.5 min-w-0 flex-1 sm:flex-none sm:min-w-[180px]">
              <Label htmlFor="simple-type" className="text-sm font-semibold">
                Type
              </Label>
              <Select
                value={typeId}
                onValueChange={(value) => onSimpleType(value as PlaygroundPresetId)}
                disabled={busy && !displayOutput}
              >
                <SelectTrigger
                  id="simple-type"
                  className="min-h-11 w-full sm:w-[200px] bg-white"
                  data-testid="simple-type-select"
                >
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  {SIMPLE_TYPES.map((item) => (
                    <SelectItem
                      key={item.id}
                      value={item.id}
                      data-testid={`simple-type-${item.id}`}
                    >
                      {item.label}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </div>

            <div
              className="space-y-1.5"
              data-testid="simple-object-count"
            >
              <Label className="text-sm font-semibold">Objects</Label>
              <div className="flex flex-wrap gap-1.5" role="group" aria-label="Number of objects">
                {SIMPLE_OBJECT_COUNTS.map((n) => (
                  <Button
                    key={n}
                    type="button"
                    size="sm"
                    variant={n === objectCount ? 'default' : 'outline'}
                    className="min-h-11 min-w-11"
                    data-testid={`simple-count-${n}`}
                    disabled={busy && !displayOutput}
                    onClick={() => onSimpleCount(n)}
                  >
                    {n}
                  </Button>
                ))}
              </div>
            </div>

            <Button
              type="button"
              className="min-h-11 w-full sm:w-auto"
              data-testid="randomize-button"
              disabled={busy && !displayOutput}
              onClick={onRandomize}
            >
              {busy && displayOutput ? (
                <Loader2 className="h-4 w-4 mr-2 animate-spin" />
              ) : (
                <Shuffle className="h-4 w-4 mr-2" />
              )}
              Randomize
            </Button>
          </div>
        </section>

        {/* Immediate output */}
        <section data-testid="results-section" className="space-y-3">
          <h2 className="text-lg font-semibold tracking-tight">Generated output</h2>
          <GeneratedOutputPanel
            output={displayOutput}
            busy={busy}
            error={error}
            testIdPrefix="tool"
            rootTypeName="Root"
            typesLanguage={typesLanguage}
            onTypesLanguageChange={setTypesLanguage}
            preClassName="max-h-[min(480px,55vh)] overflow-auto p-3 sm:p-4 text-xs font-mono whitespace-pre-wrap break-all leading-relaxed"
            onCopied={(tab) => {
              toast({ title: tab === 'json' ? 'JSON copied' : 'Types copied' })
            }}
            extraActions={
              <Button
                type="button"
                variant="outline"
                className="w-full sm:w-auto min-h-10"
                data-testid="download-json"
                disabled={displayOutput == null}
                onClick={handleDownloadRecords}
              >
                <Download className="h-4 w-4 mr-1.5" />
                Download JSON
              </Button>
            }
          />
        </section>

        {/* Advanced — collapsed by default */}
        <details className="group rounded-xl border border-border" data-testid="advanced-section">
          <summary className="cursor-pointer list-none flex items-center justify-between gap-3 px-4 py-3 sm:px-5 min-h-12 select-none">
            <span className="font-semibold text-base">Advanced</span>
            <ChevronDown className="h-4 w-4 text-muted-foreground transition-transform group-open:rotate-180" />
          </summary>
          <div className="border-t border-border px-4 sm:px-5 py-5 space-y-6">
            <p className="text-sm text-muted-foreground">
              Paste your own JSON, tune locale and list lengths, share a URL, or download Mockifyer
              scenario files.
            </p>

            <div
              className="rounded-lg border border-border bg-zinc-50/80 p-3 space-y-3"
              data-testid="size-controls"
            >
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                <div className="space-y-1.5">
                  <Label htmlFor="count" className="text-sm font-semibold">
                    Records
                  </Label>
                  <div className="flex items-center gap-2">
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="Fewer records"
                      data-testid="count-decrement"
                      disabled={busy || count <= MIN_RECORDS}
                      onClick={() => setCount((n) => clampInt(n - 1, MIN_RECORDS, MAX_RECORDS))}
                    >
                      <Minus className="h-4 w-4" />
                    </Button>
                    <Input
                      id="count"
                      data-testid="count-input"
                      type="number"
                      min={MIN_RECORDS}
                      max={MAX_RECORDS}
                      className="min-h-11 text-center text-base font-semibold bg-white"
                      value={count}
                      onChange={(e) =>
                        setCount(clampInt(Number(e.target.value), MIN_RECORDS, MAX_RECORDS))
                      }
                    />
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="More records"
                      data-testid="count-increment"
                      disabled={busy || count >= MAX_RECORDS}
                      onClick={() => setCount((n) => clampInt(n + 1, MIN_RECORDS, MAX_RECORDS))}
                    >
                      <Plus className="h-4 w-4" />
                    </Button>
                  </div>
                </div>
                <div className="space-y-1.5">
                  <Label htmlFor="item-count" className="text-sm font-semibold">
                    Items per list
                  </Label>
                  <div className="flex items-center gap-2">
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="Fewer items per list"
                      data-testid="item-count-decrement"
                      disabled={busy || itemCount <= MIN_ITEMS_PER_LIST}
                      onClick={() =>
                        setItemCount((n) =>
                          clampInt(n - 1, MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST)
                        )
                      }
                    >
                      <Minus className="h-4 w-4" />
                    </Button>
                    <Input
                      id="item-count"
                      data-testid="item-count-input"
                      type="number"
                      min={MIN_ITEMS_PER_LIST}
                      max={MAX_ITEMS_PER_LIST}
                      className="min-h-11 text-center text-base font-semibold bg-white"
                      value={itemCount}
                      onChange={(e) =>
                        setItemCount(
                          clampInt(Number(e.target.value), MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST)
                        )
                      }
                    />
                    <Button
                      type="button"
                      variant="outline"
                      size="icon"
                      className="min-h-11 min-w-11 shrink-0"
                      aria-label="More items per list"
                      data-testid="item-count-increment"
                      disabled={busy || itemCount >= MAX_ITEMS_PER_LIST}
                      onClick={() =>
                        setItemCount((n) =>
                          clampInt(n + 1, MIN_ITEMS_PER_LIST, MAX_ITEMS_PER_LIST)
                        )
                      }
                    >
                      <Plus className="h-4 w-4" />
                    </Button>
                  </div>
                </div>
              </div>
              <p className="text-sm font-medium" data-testid="size-controls-live">
                Live result: {count} record{count === 1 ? '' : 's'}
                {records ? ` → got ${records.length}` : ''} · {itemCount} item
                {itemCount === 1 ? '' : 's'} per list
              </p>
            </div>

            <div className="grid grid-cols-1 xl:grid-cols-2 gap-4 sm:gap-6 items-start">
              <div className="space-y-4 min-w-0">
                <Card className="border-border overflow-hidden" data-testid="sample-json-card">
                  <CardHeader className="pb-3">
                    <CardTitle className="text-lg">Paste or upload sample JSON</CardTitle>
                    <CardDescription>
                      Drop in a response body (or a Mockifyer mock document).
                    </CardDescription>
                  </CardHeader>
                  <CardContent className="space-y-4">
                    <div className="space-y-2" data-testid="sample-input-actions">
                      <input
                        ref={fileInputRef}
                        type="file"
                        accept="application/json,.json"
                        className="hidden"
                        onChange={(e) => void handleUpload(e.target.files?.[0] ?? null)}
                      />
                      <div className="flex flex-col sm:flex-row flex-wrap gap-2">
                        <Button
                          type="button"
                          className="w-full sm:w-auto min-h-11"
                          data-testid="upload-json-button"
                          onClick={() => fileInputRef.current?.click()}
                        >
                          <Upload className="h-4 w-4 mr-2" />
                          Upload JSON
                        </Button>
                        <Button
                          type="button"
                          variant="outline"
                          className="w-full sm:w-auto min-h-11"
                          data-testid="focus-paste-button"
                          onClick={() => {
                            const el = document.querySelector<HTMLTextAreaElement>(
                              '[data-testid="sample-json"]'
                            )
                            el?.focus()
                            el?.select()
                          }}
                        >
                          <FileJson className="h-4 w-4 mr-2" />
                          Paste JSON
                        </Button>
                        <Button
                          type="button"
                          variant="ghost"
                          className="w-full sm:w-auto min-h-11"
                          onClick={handleResetExample}
                        >
                          Reset example
                        </Button>
                      </div>
                    </div>

                    <Textarea
                      aria-label="Sample JSON"
                      data-testid="sample-json"
                      className="min-h-[160px] max-h-[260px] font-mono text-xs sm:text-sm break-all"
                      value={inputText}
                      onChange={(e) => setInputText(e.target.value)}
                      spellCheck={false}
                    />

                    <div className="space-y-2" data-testid="sample-presets">
                      <Label htmlFor="preset-select" className="text-xs text-muted-foreground">
                        Or try a built-in sample
                      </Label>
                      <Select
                        disabled={busy}
                        onValueChange={(id) => {
                          const preset = findPreset(id)
                          if (preset) void handlePreset(preset)
                        }}
                      >
                        <SelectTrigger
                          id="preset-select"
                          className="w-full min-h-11"
                          data-testid="preset-select"
                        >
                          <SelectValue placeholder="Choose a sample shape…" />
                        </SelectTrigger>
                        <SelectContent>
                          {PLAYGROUND_PRESETS.map((preset) => (
                            <SelectItem
                              key={preset.id}
                              value={preset.id}
                              data-testid={`preset-${preset.id}`}
                            >
                              {preset.label}
                              {preset.realApi ? ' · real API' : ''}
                            </SelectItem>
                          ))}
                        </SelectContent>
                      </Select>
                      <div
                        className="flex gap-1.5 overflow-x-auto pb-1 -mx-1 px-1 [scrollbar-width:thin]"
                        role="group"
                        aria-label="Quick sample presets"
                      >
                        {SIMPLE_TYPES.map((item) => {
                          const preset = findPreset(item.id)
                          if (!preset) return null
                          return (
                            <Button
                              key={item.id}
                              type="button"
                              size="sm"
                              variant="outline"
                              className="shrink-0 min-h-10"
                              disabled={busy}
                              data-testid={`preset-chip-${item.id}`}
                              onClick={() => void handlePreset(preset)}
                            >
                              {item.label}
                            </Button>
                          )
                        })}
                      </div>
                    </div>
                  </CardContent>
                </Card>

                <Card className="border-border overflow-hidden">
                  <CardHeader>
                    <CardTitle className="text-lg">Options</CardTitle>
                    <CardDescription>
                      Context steers locale and currency. Seed keeps output deterministic.
                    </CardDescription>
                  </CardHeader>
                  <CardContent className="space-y-4">
                    <div className="space-y-2">
                      <Label htmlFor="context">Context</Label>
                      <Input
                        id="context"
                        data-testid="context-input"
                        className="min-h-11"
                        placeholder="swedish users, prices in SEK"
                        value={context}
                        onChange={(e) => setContext(e.target.value)}
                      />
                    </div>
                    <div className="space-y-2">
                      <Label htmlFor="seed">Seed</Label>
                      <Input
                        id="seed"
                        data-testid="seed-input"
                        className="min-h-11"
                        value={String(seed)}
                        onChange={(e) => {
                          const raw = e.target.value
                          setSeed(/^-?\d+$/.test(raw) ? Number(raw) : raw)
                        }}
                      />
                    </div>

                    <div className="space-y-3" data-testid="chaos-slider-section">
                      <div className="flex items-center justify-between">
                        <Label htmlFor="chaos">Chaos level</Label>
                        <span
                          className="text-sm font-medium capitalize"
                          data-testid="chaos-level-label"
                        >
                          {level}
                        </span>
                      </div>
                      <input
                        id="chaos"
                        data-testid="chaos-slider"
                        type="range"
                        min={0}
                        max={CHAOS_LEVELS.length - 1}
                        step={1}
                        value={sliderIndex}
                        onChange={(e) => setLevel(CHAOS_LEVELS[Number(e.target.value)]!)}
                        className="w-full accent-primary"
                      />
                      <div className="flex justify-between text-xs text-muted-foreground">
                        {CHAOS_LEVELS.map((name) => (
                          <span key={name} className="capitalize">
                            {name}
                          </span>
                        ))}
                      </div>
                    </div>

                    <Button
                      type="button"
                      className="w-full min-h-11"
                      data-testid="generate-button"
                      disabled={busy}
                      onClick={() => void handleGenerateAdvanced()}
                    >
                      {busy ? (
                        <>
                          <Loader2 className="h-4 w-4 mr-2 animate-spin" />
                          Generating…
                        </>
                      ) : (
                        <>
                          <Sparkles className="h-4 w-4 mr-2" />
                          Generate
                        </>
                      )}
                    </Button>
                  </CardContent>
                </Card>
              </div>

              <Card className="border-border overflow-hidden min-w-0">
                <CardHeader>
                  <CardTitle className="text-lg">Inferred field kinds</CardTitle>
                  <CardDescription>
                    Edit a kind to steer generation. Overrides are included in the shareable URL.
                  </CardDescription>
                </CardHeader>
                <CardContent>
                  {fields.length === 0 ? (
                    <p className="text-sm text-muted-foreground">Paste valid JSON to infer fields.</p>
                  ) : (
                    <div className="overflow-x-auto" data-testid="field-kinds">
                      <table className="w-full text-sm">
                        <thead>
                          <tr className="border-b border-border text-left text-muted-foreground">
                            <th className="py-2 pr-4 font-medium">Path</th>
                            <th className="py-2 pr-4 font-medium">Kind</th>
                            <th className="py-2 font-medium">Confidence</th>
                          </tr>
                        </thead>
                        <tbody>
                          {structuralFields.map((field) => (
                            <tr
                              key={field.path}
                              className="border-b border-border/70"
                              data-testid={`structural-${field.path}`}
                            >
                              <td className="py-2 pr-4 font-mono text-xs">{field.path}</td>
                              <td className="py-2 pr-4 text-muted-foreground">
                                {structuralArrayLabel(field, fields)}
                                {typeof field.arrayLength === 'number'
                                  ? ` · length ${field.arrayLength}`
                                  : ''}
                              </td>
                              <td className="py-2 text-muted-foreground">—</td>
                            </tr>
                          ))}
                          {editableFields.map((field) => {
                            const current = String(overrides[field.path] ?? field.kind)
                            const options = kindOptionsIncluding(current)
                            return (
                              <tr key={field.path} className="border-b border-border/70">
                                <td className="py-2 pr-4 font-mono text-xs">{field.path}</td>
                                <td className="py-2 pr-4 min-w-[160px]">
                                  <Select
                                    value={current}
                                    onValueChange={(value) => onOverrideKind(field.path, value)}
                                  >
                                    <SelectTrigger
                                      className="h-8"
                                      aria-label={`Kind for ${field.path}`}
                                      data-testid={`kind-${field.path}`}
                                    >
                                      <SelectValue placeholder={current} />
                                    </SelectTrigger>
                                    <SelectContent>
                                      {options.map((kind) => (
                                        <SelectItem key={kind} value={kind}>
                                          {kind}
                                        </SelectItem>
                                      ))}
                                    </SelectContent>
                                  </Select>
                                </td>
                                <td className="py-2 text-muted-foreground">
                                  {overrides[field.path]
                                    ? 'override'
                                    : field.confidence.toFixed(2)}
                                </td>
                              </tr>
                            )
                          })}
                        </tbody>
                      </table>
                    </div>
                  )}
                </CardContent>
              </Card>
            </div>

            {records && (
              <div className="space-y-6">
                <Card className="border-border" data-testid="variants-section">
                  <CardHeader className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
                    <div>
                      <CardTitle className="text-xl">Edge-case variants</CardTitle>
                      <CardDescription>
                        Chaos at <span className="font-medium capitalize">{level}</span>.
                      </CardDescription>
                    </div>
                    <Button
                      type="button"
                      variant="outline"
                      size="sm"
                      data-testid="download-variants-zip"
                      disabled={namedVariants.length === 0}
                      onClick={() => void handleDownloadVariantsZip()}
                    >
                      <FileJson className="h-4 w-4 mr-1.5" />
                      Download mock files (ZIP)
                    </Button>
                  </CardHeader>
                  <CardContent className="space-y-4">
                    {namedVariants.length === 0 ? (
                      <p className="text-sm text-muted-foreground">No variants at this chaos level.</p>
                    ) : (
                      <ul className="space-y-2" data-testid="variant-list">
                        {namedVariants.map((v) => (
                          <li
                            key={v.name}
                            className="flex items-center justify-between gap-3 rounded-md border border-border px-3 py-2 text-sm"
                          >
                            <span className="font-mono text-xs">
                              {variantLabel(v.kind, v.name)}
                            </span>
                            <span className="text-muted-foreground">
                              status {v.mock.response.status}
                              {v.mock.responseDelayMs
                                ? ` · delay ${v.mock.responseDelayMs}ms`
                                : ''}
                            </span>
                          </li>
                        ))}
                      </ul>
                    )}
                  </CardContent>
                </Card>

                {namedVariants.length > 0 && (
                  <Card className="border-border" data-testid="resilience-checklist">
                    <CardHeader>
                      <CardTitle className="text-xl">Resilience checklist</CardTitle>
                      <CardDescription>
                        Your API shape has {namedVariants.length} edge case
                        {namedVariants.length === 1 ? '' : 's'}. How many does your app handle?
                      </CardDescription>
                    </CardHeader>
                    <CardContent className="space-y-3">
                      <p className="text-sm font-medium" data-testid="resilience-score">
                        {checkedCount} / {namedVariants.length} handled
                      </p>
                      <ul className="space-y-2">
                        {namedVariants.map((v) => (
                          <li key={v.name}>
                            <label className="flex items-center gap-2 text-sm cursor-pointer">
                              <input
                                type="checkbox"
                                data-testid={`checklist-${v.name}`}
                                checked={Boolean(checked[v.name])}
                                onChange={(e) =>
                                  setChecked((prev) => ({
                                    ...prev,
                                    [v.name]: e.target.checked,
                                  }))
                                }
                                className="h-4 w-4 accent-primary"
                              />
                              <span>{v.name}</span>
                            </label>
                          </li>
                        ))}
                      </ul>
                    </CardContent>
                  </Card>
                )}
              </div>
            )}

            <div className="grid grid-cols-1 lg:grid-cols-2 gap-4 sm:gap-6">
              <Card className="border-border overflow-hidden min-w-0">
                <CardHeader>
                  <CardTitle className="text-lg">Equivalent local command</CardTitle>
                </CardHeader>
                <CardContent className="space-y-4 min-w-0" data-testid="cli-commands">
                  <div className="min-w-0 overflow-x-auto">
                    <p className="text-xs font-medium text-muted-foreground mb-2">Records</p>
                    <CodeBlock code={sampleCli} language="bash" small className="max-w-full" />
                  </div>
                  <div className="min-w-0 overflow-x-auto">
                    <p className="text-xs font-medium text-muted-foreground mb-2">Variants</p>
                    <CodeBlock code={variantsCli} language="bash" small className="max-w-full" />
                  </div>
                </CardContent>
              </Card>

              <Card className="border-border overflow-hidden">
                <CardHeader>
                  <CardTitle className="text-lg">Share this setup</CardTitle>
                </CardHeader>
                <CardContent className="space-y-3">
                  <Button
                    type="button"
                    variant="outline"
                    className="w-full sm:w-auto min-h-11"
                    data-testid="copy-share-link"
                    onClick={() => void handleCopyShareLink()}
                  >
                    <Link2 className="h-4 w-4 mr-2" />
                    Copy share link
                  </Button>
                  {shareTooLarge && (
                    <p
                      className="text-sm text-amber-800 bg-amber-50 border border-amber-200 rounded-md px-3 py-2"
                      data-testid="share-too-large"
                    >
                      This sample is too large to fit in a shareable URL.
                    </p>
                  )}
                  {!isPlaygroundShareHash(
                    typeof window !== 'undefined' ? window.location.hash : ''
                  ) &&
                    !shareTooLarge && (
                      <p className="text-xs text-muted-foreground">
                        Edit options or generate to refresh the shareable hash.
                      </p>
                    )}
                </CardContent>
              </Card>
            </div>

            <RealApiDemo onUseAsSample={(example) => void handleUseRealApiSample(example)} />

            <section
              className="border border-border rounded-xl bg-zinc-50/80 px-6 py-8 sm:px-10 space-y-4"
              data-testid="record-cta"
            >
              <div className="flex items-start gap-3">
                <Radio className="h-7 w-7 text-primary shrink-0 mt-1" aria-hidden />
                <div className="space-y-2 max-w-3xl">
                  <h2 className="text-xl sm:text-2xl font-semibold tracking-tight">
                    Got a real API? Record it with Mockifyer
                  </h2>
                  <p className="text-muted-foreground text-sm sm:text-base">
                    Capture live responses once, then replay them offline.
                  </p>
                </div>
              </div>
              <div className="flex flex-wrap items-center gap-4">
                <Button asChild data-testid="record-cta-getting-started">
                  <Link to="/getting-started">
                    Start recording
                    <ArrowRight className="h-4 w-4 ml-2" />
                  </Link>
                </Button>
                <button
                  type="button"
                  className="text-sm text-primary underline-offset-4 hover:underline font-medium"
                  data-testid="record-cta-try-demo"
                  onClick={() => {
                    void navigator.clipboard.writeText(TRY_DEMO_COMMAND).then(() => {
                      toast({
                        title: 'Copied try command',
                        description: TRY_DEMO_COMMAND,
                      })
                    })
                  }}
                >
                  Or try the demo:{' '}
                  <code className="text-xs bg-white border px-1.5 py-0.5 rounded">
                    {TRY_DEMO_COMMAND}
                  </code>
                </button>
              </div>
            </section>
          </div>
        </details>

        <MockDataGeneratorSeo />
      </div>
    </div>
  )
}
