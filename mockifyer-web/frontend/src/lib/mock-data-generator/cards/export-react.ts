/**
 * Single-file React/TSX export: styles + data as props, matching playground look.
 */

import type { CardTheme, MockCard } from './types'
import { CARDS_SHARED_CSS } from './styles'

function escapeForTemplateLiteral(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function cardsLiteral(cards: MockCard[]): string {
  return JSON.stringify(cards, null, 2)
}

export interface ExportCardsReactOptions {
  cards: MockCard[]
  theme: CardTheme
  componentName?: string
}

/**
 * Returns a single `.tsx` source string: CSS-in-file + `MockCards` component.
 */
export function exportCardsReact(options: ExportCardsReactOptions): string {
  const { cards, theme, componentName = 'MockCards' } = options
  const css = escapeForTemplateLiteral(CARDS_SHARED_CSS)
  const data = cardsLiteral(cards)

  return `/**
 * Generated by Mockifyer Free Mock Data Generator.
 * Self-contained — paste into a React/TSX file. Styles match the playground cards view.
 */
import { useState, type CSSProperties } from 'react'

export interface MockCardField {
  label: string
  value: string
}

export interface MockCard {
  id: string
  kind: 'user' | 'order' | 'product' | 'generic'
  title: string
  subtitle?: string
  badge?: string
  highlight?: string
  fields: MockCardField[]
  rawJson: string
}

export type CardTheme = 'clean' | 'glass' | 'trading' | 'receipt'

const STYLES = \`${css}\`

const DEFAULT_CARDS: MockCard[] = ${data}

export interface ${componentName}Props {
  cards?: MockCard[]
  theme?: CardTheme
  /** When true, click a card to flip and show raw JSON. */
  flipEnabled?: boolean
}

export function ${componentName}({
  cards = DEFAULT_CARDS,
  theme = ${JSON.stringify(theme)},
  flipEnabled = true,
}: ${componentName}Props) {
  const [flipped, setFlipped] = useState<Record<string, boolean>>({})

  return (
    <div className={\`mdg-cards-root mdg-theme-\${theme}\`}>
      <style>{STYLES}</style>
      <div className="mdg-cards-grid">
        {cards.map((card, index) => {
          const isFlipped = Boolean(flipped[card.id])
          const delay: CSSProperties = {
            animationDelay: \`\${Math.min(index, 12) * 55}ms\`,
          }
          return (
            <article
              key={card.id}
              className={\`mdg-card-scene mdg-enter\${isFlipped ? ' is-flipped' : ''}\`}
              style={delay}
              onClick={() => {
                if (!flipEnabled) return
                setFlipped((prev) => ({ ...prev, [card.id]: !prev[card.id] }))
              }}
              role={flipEnabled ? 'button' : undefined}
              tabIndex={flipEnabled ? 0 : undefined}
              onKeyDown={(event) => {
                if (!flipEnabled) return
                if (event.key === 'Enter' || event.key === ' ') {
                  event.preventDefault()
                  setFlipped((prev) => ({ ...prev, [card.id]: !prev[card.id] }))
                }
              }}
            >
              <div className="mdg-card-flip">
                <div className="mdg-card-face mdg-card-front">
                  <div className="mdg-card-kicker">{card.kind}</div>
                  <h3 className="mdg-card-title">{card.title}</h3>
                  {card.subtitle ? <p className="mdg-card-sub">{card.subtitle}</p> : null}
                  {card.badge ? <span className="mdg-card-badge">{card.badge}</span> : null}
                  {card.fields.length > 0 ? (
                    <ul className="mdg-card-fields">
                      {card.fields.map((field) => (
                        <li key={field.label}>
                          <span className="lbl">{field.label}</span>
                          <span className="val">{field.value}</span>
                        </li>
                      ))}
                    </ul>
                  ) : null}
                  {card.highlight ? (
                    <div className="mdg-card-highlight mdg-count">{card.highlight}</div>
                  ) : null}
                </div>
                <div className="mdg-card-face mdg-card-back">
                  <div className="mdg-card-kicker">JSON</div>
                  <pre>{card.rawJson}</pre>
                </div>
              </div>
            </article>
          )
        })}
      </div>
    </div>
  )
}

export default ${componentName}
`
}
